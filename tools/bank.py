#!/usr/bin/env python3
"""The question bank lives in data/bank/, split so the practice app can load one section at a time:

    data/bank/q-<subject>.js   single questions for gc, oc, pm, bc, bio, beh, cars
    data/bank/p-<section>.js   passages for cp, cars, bb, ps

Each file is one JavaScript statement that pushes its items onto window.BANK, one item per line, so git
diffs show exactly which questions changed. Always use load() and save() here instead of editing by hand.
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIR = ROOT / "data" / "bank"
QS = ["gc", "oc", "pm", "bc", "bio", "beh", "cars"]       # single-question files, by subject
PS = ["cp", "cars", "bb", "ps"]                            # passage files, by MCAT section
CHUNKS = [f"q-{s}" for s in QS] + [f"p-{s}" for s in PS]
HEAD = "/* Pre-Med Pulse question bank ({name}). Generated by tools/bank.py: edit through load()/save(). Never rename or remove an id; add new passage questions at the end of a passage. */"

def path(name): return DIR / f"{name}.js"

def _items(name):
    t = path(name).read_text(encoding="utf-8")
    m = re.search(r"\.push\(\.\.\.(\[.*\])\);\s*$", t, re.S)
    if not m: raise SystemExit(f"{path(name)} is not in the expected format")
    return json.loads(m.group(1))

def load():
    """(Q, P): every single question, then every passage, in chunk order."""
    Q = [x for s in QS for x in _items(f"q-{s}")]
    P = [x for s in PS for x in _items(f"p-{s}")]
    return Q, P

def src():
    """All chunk files as one string (for the cache stamp)."""
    return "\n".join(path(n).read_text(encoding="utf-8") for n in CHUNKS)

def _write(name, kind, items):
    body = "[\n" + ",\n".join(json.dumps(x, ensure_ascii=False) for x in items) + "\n]"
    path(name).write_text(f'{HEAD.format(name=name)}\n(window.BANK=window.BANK||{{q:[],p:[],got:{{}}}}).got["{name}"]=1;\nBANK.{kind}.push(...{body});\n', encoding="utf-8")

def save(name, items):
    """save("Q", all_single_questions) or save("P", all_passages): rewrites the matching chunk files."""
    DIR.mkdir(parents=True, exist_ok=True)
    if name == "Q":
        bad = {q.get("subj") for q in items} - set(QS)
        if bad: raise SystemExit(f"unknown subject(s) {bad}")
        for s in QS: _write(f"q-{s}", "q", [q for q in items if q["subj"] == s])
    elif name == "P":
        bad = {p.get("s") for p in items} - set(PS)
        if bad: raise SystemExit(f"unknown section(s) {bad}")
        for s in PS: _write(f"p-{s}", "p", [p for p in items if p["s"] == s])
    else:
        raise SystemExit("save() takes 'Q' or 'P'")
